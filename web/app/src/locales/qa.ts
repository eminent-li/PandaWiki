export const getQaMessages = (language: QaLanguage) =>
  qaMessages[language] || qaMessages['zh-CN'];

const DEFAULT_ANSWER_DISCLAIMER_VARIANTS = new Set<string>([
  qaMessages['zh-CN'].answerDisclaimer,
  '本回答由 PandaWiki 基于 AI 生成，仅供参考。',
  qaMessages['en-US'].answerDisclaimer,
  'This answer was generated by PandaWiki AI and is for reference only.',
]);

const DEFAULT_SUPPORT_BY_VARIANTS = new Set<string>([
  qaMessages['zh-CN'].supportBy,
  qaMessages['en-US'].supportBy,
]);

const normalizeLocaleValue = (value?: string | null) => value?.trim() ?? '';

export const resolveQaAnswerDisclaimer = (
  language: QaLanguage,
  value?: string | null,
) => {
  const normalized = normalizeLocaleValue(value);
  if (!normalized || DEFAULT_ANSWER_DISCLAIMER_VARIANTS.has(normalized)) {
    return getQaMessages(language).answerDisclaimer;
  }
  return value ?? '';
};

export const resolveQaSupportBy = (
  language: QaLanguage,
  value?: string | null,
) => {
  const normalized = normalizeLocaleValue(value);
  if (!normalized || DEFAULT_SUPPORT_BY_VARIANTS.has(normalized)) {
    return getQaMessages(language).supportBy;
  }
  return value ?? '';
};
